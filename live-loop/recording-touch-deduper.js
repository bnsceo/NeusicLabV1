(() => {
  'use strict';

  const recentTouch = new WeakMap();
  const WINDOW_MS = 1500;

  document.addEventListener('pointerdown', event => {
    const button = event.target.closest?.('.loop-track [data-action="record"]');
    if (!button || event.pointerType === 'mouse') return;
    recentTouch.set(button, performance.now());
  }, {capture:true, passive:true});

  document.addEventListener('click', event => {
    const button = event.target.closest?.('.loop-track [data-action="record"]');
    if (!button) return;

    const touchedAt = recentTouch.get(button);
    if (touchedAt === undefined) return;

    const elapsed = performance.now() - touchedAt;
    recentTouch.delete(button);
    if (elapsed > WINDOW_MS) return;

    // The trusted pointerdown handler in app.js already started/stopped REC.
    // Suppress only the synthetic follow-up click generated by touch/pen input.
    event.preventDefault();
    event.stopImmediatePropagation();
  }, true);
})();
